function packU16BE(arr) {
  return (
    "hex\"" +
    arr
      .map((n) => {
        if (n < 0 || n > 0xffff) throw new Error("out of uint16 range");
        return n.toString(16).padStart(4, "0"); // big-endian 2 bytes
      })
      .join("") +
    "\""
  );
}

